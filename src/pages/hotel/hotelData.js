const resolveImageUrl = (value) => {
  const raw = String(value || '').trim();
  if (!raw) return '';

  if (/^https?:\/\//i.test(raw)) {
    return raw;
  }

  if (/^(data:|blob:)/i.test(raw)) {
    return raw;
  }

  const normalized = raw.replace(/\\/g, '/');
  const origin = typeof window !== 'undefined' ? window.location.origin : '';
  if (!origin) return normalized;

  const path = normalized.startsWith('/') ? normalized : `/${normalized}`;
  return `${origin}${path}`;
};

const normalizeImageList = (images = []) => {
  const input = Array.isArray(images) ? images : [images];
  return input
    .map((item) => resolveImageUrl(item))
    .filter(Boolean);
};

const normalizeRows = (payload) => {
  if (Array.isArray(payload)) return payload;
  if (Array.isArray(payload?.data)) return payload.data;
  if (Array.isArray(payload?.rows)) return payload.rows;
  if (Array.isArray(payload?.result)) return payload.result;
  return [];
};

const toQueryString = (filters = {}) => {
  const query = new URLSearchParams();
  Object.entries(filters || {}).forEach(([key, value]) => {
    if (value === undefined || value === null) return;
    const text = String(value).trim();
    if (text === '') return;
    query.set(key, text);
  });
  return query.toString();
};

const parseCoordinate = (value) => {
  const numeric = Number(value);
  return Number.isFinite(numeric) ? numeric : null;
};

export async function fetchHotelCatalog(filters = {}) {
  try {
    const query = toQueryString(filters);
    const url = `${API_BASE}/hotel.php?action=list&no_auth=true${query ? `&${query}` : ''}`;
    const response = await fetch(url);
    const payload = await response.json();
    if (!response.ok || payload?.success === false) {
      throw new Error(payload?.message || 'Failed to load hotel catalog');
    }
    return normalizeRows(payload).map(normalizeHotelRecord).filter(Boolean);
  } catch (error) {
    return HOTEL_CATALOG;
  }
}

export async function fetchHotelDestinations() {
  try {
    const response = await fetch(`${API_BASE}/hotel.php?action=meta&no_auth=true`);
    const payload = await response.json();
    if (!response.ok || payload?.success === false) {
      throw new Error(payload?.message || 'Failed to load destinations');
    }

    const rows = Array.isArray(payload?.options?.destinations) ? payload.options.destinations : [];
    return rows.map((item) => ({
      name: item.name,
      hotels: `${Number(item.hotel_count || 0)} khách sạn`,
      hotel_count: Number(item.hotel_count || 0),
      slug: String(item.slug || ''),
      destination_id: Number(item.destination_id || 0),
      thumbnail_url: resolveImageUrl(item.thumbnail_url),
      image: resolveImageUrl(item.thumbnail_url),
    }));
  } catch (error) {
    try {
      const response = await fetch(`${API_BASE}/hotel.php?action=get_destinations&no_auth=true`);
      const payload = await response.json();
      if (!response.ok || payload?.success === false) {
        throw new Error(payload?.message || 'Failed to load destinations');
      }

      const rows = normalizeRows(payload);
      return rows.map((item) => ({
        name: item.name,
        hotels: `${Number(item.hotel_count || 0)} khách sạn`,
        hotel_count: Number(item.hotel_count || 0),
        slug: String(item.slug || ''),
        destination_id: Number(item.destination_id || 0),
        thumbnail_url: resolveImageUrl(item.thumbnail_url),
        image: resolveImageUrl(item.thumbnail_url),
      }));
    } catch (innerError) {
      return HOTEL_DESTINATIONS.map((name) => ({
        name,
        hotels: '',
        hotel_count: 0,
        slug: '',
        destination_id: 0,
        thumbnail_url: '',
        image: '',
      }));
    }
  }
}

export async function fetchHotelBySlug(slug) {
  if (!slug) return null;
  try {
    const response = await fetch(`${API_BASE}/hotel.php?action=get&no_auth=true&slug=${encodeURIComponent(slug)}`);
    const payload = await response.json();
    if (!response.ok || payload?.success === false) {
      throw new Error(payload?.message || 'Failed to load hotel detail');
    }
    return normalizeHotelRecord(payload?.data || payload?.hotel || null);
  } catch (error) {
    return findHotelBySlug(slug);
  }
}

export async function submitHotelBooking(data = {}) {
  const response = await fetch(`${API_BASE}/hotel.php?action=book&no_auth=true`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(data),
  });
  const payload = await response.json();
  if (!response.ok || payload?.success === false) {
    throw new Error(payload?.message || 'Booking failed');
  }
  return payload;
}

export async function fetchHotelBookingByCode(randomCode) {
  const bookingCode = String(randomCode || '').trim();
  if (!bookingCode) return null;

  const response = await fetch(`${API_BASE}/hotel.php?action=get_one_hotel_booking&no_auth=true&random_code=${encodeURIComponent(bookingCode)}`);
  const payload = await response.json();
  if (!response.ok || payload?.success === false) {
    throw new Error(payload?.message || 'Failed to load hotel booking');
  }
  const booking = payload?.data || null;
  if (!booking || typeof booking !== 'object') return booking;

  return {
    ...booking,
    cover_image_url: resolveImageUrl(booking.cover_image_url),
  };
}

export function formatHotelPrice(value) {
  const amount = Number(value || 0);
  if (!Number.isFinite(amount) || amount <= 0) return '';
  return `${new Intl.NumberFormat('us-US').format(amount)} đ`;
}

// hàm in số điện thoại theo định dạng [n].[3].[4]
export function formatPhoneNumber(value) {
  const raw = String(value || '').trim();
  if (!raw) return '';
  if (raw.length >= 10) {
    return `${raw.slice(0, raw.length - 7)}.${raw.slice(3, 6)}.${raw.slice(6)}`;
  }
  return raw;
}

// hàm hiển thị dd-mm-yyyy
export function formatDateDMY(value) {
  const date = new Date(value);
  if (isNaN(date.getTime())) return '';
  const day = String(date.getDate()).padStart(2, '0');
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const year = String(date.getFullYear());
  return `${day}-${month}-${year}`;
}

