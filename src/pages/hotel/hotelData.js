export function normalizeHotelRecord(record) {
  if (!record || typeof record !== 'object') return null;

  const slug = String(
    record.slug ||
    record.hotel_slug ||
    record.hotel_id ||
    record.id ||
    record.name ||
    ''
  ).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

  const imagesRaw = Array.isArray(record.images)
    ? record.images
    : [record.image, record.photo, record.cover_image, record.cover_image_url].filter(Boolean);
  const images = normalizeImageList(imagesRaw);

  return {
    hotel_id: record.hotel_id ?? record.id ?? slug,
    slug,
    name: record.name || record.hotel_name || record.title || '',
    city: record.city || record.destination || '',
    area: record.area || record.neighborhood || '',
    address: record.address || record.hotel_address || '',
    stars: Number(record.stars ?? record.star ?? 0),
    rating: Number(record.rating ?? record.score ?? 0),
    reviews: Number(record.reviews ?? record.review_count ?? 0),
    price: Number(record.price ?? record.price_vnd ?? 0),
    price_text: record.price_text || record.price_text_vnd || '',
    old_price: Number(record.old_price ?? record.old_price_vnd ?? 0),
    package_name: record.package_name || record.package || '',
    meal: record.meal || record.meal_text || '',
    tags: Array.isArray(record.tags) ? record.tags : [],
    highlights: Array.isArray(record.highlights) ? record.highlights : [],
    images,
    deal_badge: record.deal_badge || record.badge || '',
    sale_badge: record.sale_badge || record.saleText || '',
    departure_points: Array.isArray(record.departure_points) ? record.departure_points : [],
    lat: parseCoordinate(record.lat ?? record.latitude),
    lng: parseCoordinate(record.lng ?? record.longitude),
    description: record.description || '',
  };
}

export function filterHotels(hotels, filters = {}) {
  const keyword = String(filters.keyword || '').trim().toLowerCase();
  const destination = String(filters.destination || '').trim().toLowerCase();
  const budget = String(filters.budget || 'all');
  const stars = String(filters.stars || 'all');
  const style = String(filters.style || '').trim().toLowerCase();

  return (hotels || []).filter((hotel) => {
    const searchable = [hotel.name, hotel.city, hotel.area, hotel.address, ...(hotel.tags || []), ...(hotel.highlights || [])]
      .join(' ')
      .toLowerCase();

    if (keyword && !searchable.includes(keyword)) return false;
    if (destination && !searchable.includes(destination)) return false;
    if (stars !== 'all' && String(hotel.stars || '') !== stars) return false;

    if (budget !== 'all') {
      const price = Number(hotel.price || 0);
      const budgetMap = {
        under1500: price < 1500000,
        '1500to2500': price >= 1500000 && price < 2500000,
        '2500to4000': price >= 2500000 && price < 4000000,
        over4000: price >= 4000000,
      };

      if (!budgetMap[budget]) return false;
    }

    if (style) {
      const styleMatch = [hotel.package_name, hotel.meal, ...(hotel.tags || [])].join(' ').toLowerCase();
      if (!styleMatch.includes(style)) return false;
    }

    return true;
  });
}
